def club_entry(name, email, industry, region, note):
    return {
        "slug": slug(name),
        "name": name,
        "type": "corporate" if region in ("Canada",) else "business",
        "industry": industry,
        "region": region,
        "source": "club-list",
        "priority": 2 if email else 3,
        "amount": "Ask: cash, in-kind or both",
        "deadline": "Rolling",
        "deadlineDate": None,
        "applyMethod": "email" if email else "find-contact",
        "applyUrl": "",
        "email": email,
        "website": "",
        "summary": f"Potential sponsor from the club's outreach list ({region}).",
        "angle": ANGLES[industry].format(name=name),
        "eligibility": [],
        "funds": [],
        "excludes": [],
        "questions": [],
        "requiredDocs": ["Sponsorship package (PDF) with tiers", "Short intro email"],
        "notes": note,
        "sources": [],
        "verified": bool(email),
        "lastChecked": TODAY,
    }

