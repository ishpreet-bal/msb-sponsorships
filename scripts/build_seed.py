def researched_entry(d):
    base = {
        "slug": slug(d["name"]), "source": "research", "verified": True, "lastChecked": TODAY,
    }
    base.update(d)
    return base

def main():
    entries = [researched_entry(d) for d in RESEARCHED]
    seen = {e["slug"] for e in entries}
    # RBC from list duplicates researched RBC; fold its note in.
    for row in CLUB_LIST:
        e = club_entry(*row)
        if e["slug"] in ("rbc", "td"):
            continue
        if e["slug"] in seen:
            continue
        seen.add(e["slug"])
        entries.append(e)
    out = pathlib.Path(__file__).resolve().parent.parent / "data" / "opportunities.json"
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps({"updated": TODAY, "opportunities": entries}, indent=2, ensure_ascii=False))
    print(len(entries), "opportunities written")

